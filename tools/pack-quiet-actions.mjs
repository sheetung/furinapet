// Mechanical sprite packing only. Artwork comes from imagegen; no poses are synthesized here.
import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const deps = process.argv[2];
const require = createRequire(deps ? path.join(deps, 'package.json') : import.meta.url);
const sharp = require('sharp');
const { PNG } = require('pngjs');
const base = path.join(root, 'characters/furina/animations');
const cell = (name, index) => sharp(path.join(base, 'standard', name + '.png'))
  .extract({ left: index % 4 * 192, top: Math.floor(index / 4) * 208, width: 192, height: 208 }).png().toBuffer();
const neutral = await cell('idle', 0), holding = await cell('tea', 0);
const packed = {};
for (const [name, source] of [['breathing', 'breathing-strip'], ['nod', 'nod-strip'], ['tea-enter', 'tea-pickup-strip']]) {
  const file = path.join(base, 'quiet-actions-source', source + '.png');
  const { data, info } = await sharp(file).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const bounds = [];
  for (let index = 0; index < 6; index++) {
    const left = Math.round(index * info.width / 6), right = Math.round((index + 1) * info.width / 6);
    let top = info.height, bottom = 0;
    for (let y = 0; y < info.height; y++) for (let x = left; x < right; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 128) { top = Math.min(top, y); bottom = Math.max(bottom, y + 1); }
    }
    if (bottom <= top) throw Error('Empty source frame: ' + name);
    let footLeft = right, footRight = left;
    for (let y = bottom - 24; y < bottom; y++) for (let x = left; x < right; x++) {
      if (data[(y * info.width + x) * 4 + 3] > 128) { footLeft = Math.min(footLeft, x); footRight = Math.max(footRight, x); }
    }
    bounds.push({ left, top, width: right - left, height: bottom - top, footX: (footLeft + footRight) / 2 - left });
  }
  // One scale for the whole animation; never fit each pose separately.
  const scale = 190 / bounds[0].height;
  const frames = [];
  for (const b of bounds) {
    const width = Math.round(b.width * scale), height = Math.round(b.height * scale);
    if (height > 200 || width > 192) throw Error('Packing would clip the character: ' + name);
    const crop = await sharp(file).extract({ left: b.left, top: b.top, width: b.width, height: b.height })
      .resize(width, height, { kernel: 'nearest' }).png().toBuffer();
    frames.push(await sharp({ create: { width: 192, height: 208, channels: 4, background: '#00000000' } })
      .composite([{ input: crop, left: Math.round(96 - b.footX * scale), top: 200 - height }]).png().toBuffer());
  }
  // Exact authored boundary cells, not generated approximations, prevent endpoint drift.
  frames[0] = neutral;
  frames[5] = name === 'tea-enter' ? holding : neutral;
  packed[name] = frames;
}
packed['tea-exit'] = [...packed['tea-enter']].reverse();
packed['tea-exit'][0] = await cell('tea', 5);
packed['tea-sip'] = await Promise.all(Array.from({ length: 6 }, (_, index) => cell('tea', index)));
for (const [name, frames] of Object.entries(packed)) {
  const atlas = new PNG({ width: 768, height: 832 });
  for (let index = 0; index < frames.length; index++) {
    const frame = PNG.sync.read(frames[index]), left = index % 4 * 192, top = Math.floor(index / 4) * 208;
    for (let y = 0; y < 208; y++) frame.data.copy(atlas.data, ((top + y) * 768 + left) * 4, y * 192 * 4, (y + 1) * 192 * 4);
  }
  const sheet = PNG.sync.write(atlas, { colorType: 6 });
  await writeFile(path.join(base, 'quiet-actions-source', name + '.png'), sheet);
  await writeFile(path.join(base, 'standard', name + '.png'), sheet);
}
// Register packed master cells so the existing exporter/checker remains reproducible.
const recipePath = path.join(base, 'source-frames.json');
const recipe = JSON.parse(await readFile(recipePath, 'utf8'));
for (const name of Object.keys(packed)) {
  recipe.sources[name] = Array.from({ length: 6 }, (_, index) => ({ source: `animations/quiet-actions-source/${name}.png`,
    x: index % 4 * 192, y: Math.floor(index / 4) * 208, width: 192, height: 208, anchorX: 96, anchorY: 200, scale: 1 }));
  recipe.actions[name] = name;
}
await writeFile(recipePath, JSON.stringify(recipe, null, 2) + '\n');
const countsPath = path.join(root, 'characters/furina/standard-sheets.ts');
const counts = Object.fromEntries(Object.entries(recipe.actions).map(([name, source]) => [name, recipe.sources[source].length]));
await writeFile(countsPath, '// Generated by tools/build-furina-sheets.py.\nexport const standardSheetFrameCounts = ' + JSON.stringify(counts, null, 2) + ' as const;\n');
console.log('Packed five independent standard sheets; shared scale, fixed feet and authored endpoints.');
